-- 1. Tabla de configuración de la tienda
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT
);

-- 2. Tabla de galería (Módulo de Presentación: fotos y videos)
CREATE TABLE IF NOT EXISTS gallery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK(type IN ('image', 'video')),
  filepath TEXT NOT NULL,
  title TEXT DEFAULT '',
  description TEXT DEFAULT '',
  sort_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabla de enlaces a redes sociales
CREATE TABLE IF NOT EXISTS social_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  platform TEXT NOT NULL,
  url TEXT NOT NULL,
  icon TEXT DEFAULT '',
  sort_order INT DEFAULT 0
);

-- 4. Tabla de servicios y precios
CREATE TABLE IF NOT EXISTS services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT DEFAULT '',
  duration INT DEFAULT 30,
  price NUMERIC DEFAULT 0,
  active INT DEFAULT 1
);

-- 5. Tabla de barberos
CREATE TABLE IF NOT EXISTS barbers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  photo TEXT DEFAULT '',
  speciality TEXT DEFAULT '',
  active INT DEFAULT 1
);

-- 6. Tabla de horarios (Mañana, Tarde, Noche)
CREATE TABLE IF NOT EXISTS schedule_config (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period TEXT NOT NULL CHECK(period IN ('morning', 'afternoon', 'night')),
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  slot_duration INT DEFAULT 30
);

-- 7. Tabla de reservas
CREATE TABLE IF NOT EXISTS reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_name TEXT NOT NULL,
  client_phone TEXT NOT NULL,
  service_id BIGINT REFERENCES services(id) ON DELETE SET NULL,
  barber_id BIGINT REFERENCES barbers(id) ON DELETE SET NULL,
  reservation_date DATE NOT NULL,
  reservation_time TEXT NOT NULL,
  period TEXT DEFAULT '',
  status TEXT DEFAULT 'pending' CHECK(status IN ('pending', 'confirmed', 'completed', 'cancelled')),
  whatsapp_sent INT DEFAULT 0,
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

